func scoredSubmission(t *testing.T, files map[string]string) domain.AISubmissionResult {
	t.Helper()
	sub := writeStyleSubmission(t, t.TempDir(), "example", files)
	prints := engine.FingerprintSubmissions([]domain.Submission{sub}, "lab.c", similarityConfig)
	report, err := engine.ComputeAIDetectionFromFingerprints([]domain.Submission{sub}, prints, "lab.c", nil, similarityConfig)
	if err != nil {
		t.Fatal(err)
	}
	return report.Submissions[0]
}

func TestOverallAIScoreExplainsTheTotalAndNamedFiles(t *testing.T) {
	result := scoredSubmission(t, map[string]string{"lab.c": studentStyled, "helper.c": assistantStyled})
	if result.AIScore == nil || result.AIScore.Method != "heuristic-v1" {
		t.Fatalf("missing versioned score: %+v", result)
	}
	total := 0.0
	for _, contribution := range result.AIScore.Contributions {
		total += contribution.Points
	}
	if math.Abs(total-result.AIScore.Score) > 0.001 || math.Abs(result.AIScore.Score-result.Style.Score*100) > 0.001 {
		t.Fatalf("contributions %.3f, score %.3f, style %.3f", total, result.AIScore.Score, result.Style.Score)
	}
	for _, key := range []string{"prose_comments", "doc_headers", "error_checks", "defensive_idioms"} {
		feature := styleFeature(t, result.Style, key)
		if len(feature.Locations) == 0 || feature.LocationCount < len(feature.Locations) {
			t.Fatalf("%s has no locations: %+v", key, feature)
		}
		foundHelper := false
		for _, location := range feature.Locations {
			text := map[string]string{"lab.c": studentStyled, "helper.c": assistantStyled}[location.File]
			if text == "" || location.StartLine < 1 || location.EndLine < location.StartLine || location.EndLine > len(strings.Split(text, "\n")) || location.Snippet == "" {
				t.Fatalf("invalid source location: %+v", location)
			}
			foundHelper = foundHelper || location.File == "helper.c"
		}
		if !foundHelper {
			t.Fatalf("%s lost helper.c attribution", key)
		}
	}
}

